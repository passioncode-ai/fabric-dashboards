const dictionaries: Record<Lang, Record<Key, string>> = { en, ru };

export function langFor(locale: string | undefined): Lang {
  return (locale ?? '').toLowerCase().startsWith('ru') ? 'ru' : 'en';
}

export function t(lang: Lang, key: Key | string, params: Record<string, string | number> = {}): string {
  const template = dictionaries[lang][key as Key] ?? en[key as Key] ?? key;
  return template.replace(/\{(\w+)\}/g, (_, name: string) => (name in params ? String(params[name]) : `{${name}}`));
}

export function hasKey(key: string): key is Key {
  return key in en;
}

export function duration(lang: Lang, ms: number): string {
  const s = Math.max(0, Math.round(ms / 1000));
  if (s < 60) return t(lang, 'duration.s', { n: s });
  if (s < 3600) return t(lang, 'duration.m', { n: Math.round(s / 60) });
  if (s < 86400) return t(lang, 'duration.h', { n: Math.round(s / 3600) });
  return t(lang, 'duration.d', { n: Math.round(s / 86400) });
}

export const allKeys = (): Key[] => Object.keys(en) as Key[];
export const dictionary = (lang: Lang): Record<Key, string> => dictionaries[lang];
